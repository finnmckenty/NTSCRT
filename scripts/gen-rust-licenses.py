#!/usr/bin/env python3
"""Collect the license texts of every Rust crate compiled into the two
dylibs NTSCRT ships (ntscrs_capi and librashader), into
licenses/rust-crates.txt.

MIT, BSD, Zlib and similar licenses ask that their copyright notice travel
with binary copies, so the DMG carries this file. Identical texts are
printed once, under every crate that uses them.

Usage:
    scripts/gen-rust-licenses.py <librashader checkout at the pinned commit>

Needs a rustup stable toolchain (Homebrew's cargo can't run here) and
network access the first time, for cargo to fetch the crates' sources.
"""
import hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARGO = os.path.expanduser("~/.rustup/toolchains/stable-aarch64-apple-darwin/bin/cargo")
RUSTC = os.path.expanduser("~/.rustup/toolchains/stable-aarch64-apple-darwin/bin/rustc")
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.I)


def metadata(workdir, extra):
    out = subprocess.run([CARGO, "metadata", "--format-version", "1",
                          "--filter-platform", "aarch64-apple-darwin", *extra],
                         cwd=workdir, check=True, capture_output=True, text=True,
                         env={**os.environ, "RUSTC": RUSTC}).stdout
    return json.loads(out)


def linked(meta, root_name):
    """Crates reachable from `root_name` through normal (linked) deps."""
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(i for i, p in pkgs.items() if p["name"] == root_name)
    seen, stack = set(), [root]
    while stack:
        x = stack.pop()
        if x in seen:
            continue
        seen.add(x)
        for d in nodes[x]["deps"]:
            if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    return [pkgs[i] for i in seen]


def license_texts(pkg):
    """The crate's own license files, plus those of C/C++ code a -sys crate
    vendors (glslang, SPIRV-Cross), which may sit deeper."""
    top = os.path.dirname(pkg["manifest_path"])
    found = []
    for dirpath, dirnames, files in os.walk(top):
        depth = dirpath[len(top):].count(os.sep)
        if depth > (4 if pkg["name"].endswith("-sys") else 0):
            dirnames[:] = []
            continue
        dirnames[:] = [d for d in dirnames if d not in ("target", ".git", "tests", "test", "examples")]
        for f in sorted(files):
            if LICENSE_FILE.match(f):
                path = os.path.join(dirpath, f)
                with open(path, errors="replace") as fh:
                    found.append((os.path.relpath(path, top), fh.read().strip()))
    return found


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    crates = {}
    for workdir, root, extra in [
        (os.path.join(ROOT, "Vendor/ntscrs-capi"), "ntscrs-capi", ["--locked"]),
        (sys.argv[1], "librashader-capi", ["--features", "stable"]),
    ]:
        for p in linked(metadata(workdir, extra), root):
            crates[(p["name"], p["version"])] = p

    texts, users, missing = {}, {}, []
    for key in sorted(crates):
        p = crates[key]
        found = license_texts(p)
        if not found:
            missing.append(p)
        for rel, text in found:
            h = hashlib.sha1(text.encode()).hexdigest()
            texts[h] = text
            users.setdefault(h, []).append(f"{p['name']} {p['version']} ({rel})")

    out = ["Third-party Rust crates compiled into NTSCRT's bundled libraries",
           "(ntscrs_capi.dylib and librashader.dylib), with their licenses.",
           "Generated by scripts/gen-rust-licenses.py — do not edit by hand.", "",
           "Crates and their declared licenses:", ""]
    for key in sorted(crates):
        p = crates[key]
        out.append(f"  {p['name']} {p['version']} — {p['license'] or 'see license file'}")
    if missing:
        out += ["", "Crates without a license file in their package (the declared",
                "license applies; standard texts are in this folder):", ""]
        out += [f"  {p['name']} {p['version']} — {p['license']}" for p in missing]
    for h, text in texts.items():
        out += ["", "=" * 78, "Used by:"] + [f"  {u}" for u in users[h]] + ["-" * 78, text]
    dest = os.path.join(ROOT, "licenses", "rust-crates.txt")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{len(crates)} crates, {len(texts)} distinct license texts, "
          f"{len(missing)} without a file → {os.path.relpath(dest, ROOT)}")


if __name__ == "__main__":
    main()
