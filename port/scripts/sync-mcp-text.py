#!/usr/bin/env python3
"""Regenerate port/app/src/cli/mcp_text.rs from the Mac's MCPServer.swift:
the server instructions and the ntscrt_guide topics, word for word, with the
few Mac-only phrases swapped for Windows ones (WINDOWS below).

    python3 port/scripts/sync-mcp-text.py
"""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
swift = (root / "Sources/CrtApp/CLI/MCPServer.swift").read_text()
out = root / "port/app/src/cli/mcp_text.rs"

# Mac wording -> Windows wording. Every entry must still match the Swift text,
# so a reworded original is caught here instead of slipping through.
WINDOWS = [
    ("(on a Mac: select it in Finder and press Option-Command-C)",
     "(on Windows: select it in File Explorer and press Ctrl+Shift+C, or right-click it and choose Copy as path)"),
]

def dedent(block):
    lines = block.split("\n")
    pad = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
    return "\n".join(l[pad:] for l in lines).strip("\n")

guide_src = re.search(r"static let guide:.*?= \[(.*?)\n    \]\n", swift, re.S).group(1)
topics = re.findall(r'\("(\w+)", "([^"]*)", """\n(.*?)\n\s*"""\)', guide_src, re.S)
if not topics:
    sys.exit("no guide topics found in MCPServer.swift")
instructions = dedent(re.search(r'static let instructions = """\n(.*?)\n\s*"""', swift, re.S).group(1))

for mac, win in WINDOWS:
    if mac not in instructions and not any(mac in t[2] for t in topics):
        sys.exit(f"Mac phrase no longer in MCPServer.swift: {mac!r}; update WINDOWS")
    instructions = instructions.replace(mac, win)
    topics = [(i, t, x.replace(mac, win)) for i, t, x in topics]

def lit(s):
    return json.dumps(s, ensure_ascii=False)

rs = ["//! Generated by port/scripts/sync-mcp-text.py from Sources/CrtApp/CLI/MCPServer.swift: don't edit by hand.", ""]
rs.append(f"pub const INSTRUCTIONS: &str = {lit(instructions)};")
rs.append("")
rs.append("/// The craft notes, by topic (id, title, text): what ntscrt_guide returns.")
rs.append(f"pub const GUIDE: [(&str, &str, &str); {len(topics)}] = [")
for i, t, x in topics:
    rs.append(f"    ({lit(i)}, {lit(t)}, {lit(dedent(x))}),")
rs.append("];")
out.write_text("\n".join(rs) + "\n")
print(f"wrote {out.relative_to(root)}: {len(topics)} topics")
