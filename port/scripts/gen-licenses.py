#!/usr/bin/env python3
"""Collect the license texts of every Rust crate linked into the Windows app
(ntscrt.exe) into port/licenses/rust-crates-windows.txt, the way
scripts/gen-rust-licenses.py does for the Mac's dylibs. MIT, BSD, Zlib and
similar licenses ask that their notice travel with binary copies, so the
Windows package carries this file. Fails if a copyleft license appears.

Usage (from anywhere): port/scripts/gen-licenses.py
Needs the rustup stable toolchain and the crates fetched (a build does that).
"""
import hashlib, json, os, re, subprocess, sys

PORT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARGO = os.path.expanduser("~/.rustup/toolchains/stable-aarch64-apple-darwin/bin/cargo")
if not os.path.exists(CARGO):
    CARGO = "cargo"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.I)
COPYLEFT = re.compile(r"\b(A?GPL|LGPL)", re.I)


def main():
    meta = json.loads(subprocess.run(
        [CARGO, "metadata", "--format-version", "1", "--filter-platform", "x86_64-pc-windows-msvc"],
        cwd=PORT, check=True, capture_output=True, text=True).stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(i for i, p in pkgs.items() if p["name"] == "ntscrt")
    seen, stack = set(), [root]
    while stack:
        x = stack.pop()
        if x in seen:
            continue
        seen.add(x)
        for d in nodes[x]["deps"]:
            if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    crates = sorted((pkgs[i] for i in seen if pkgs[i]["source"]), key=lambda p: (p["name"], p["version"]))

    texts, users, missing, copyleft = {}, {}, [], []
    for p in crates:
        lic = p["license"] or ""
        # "MIT OR LGPL" is fine (we take MIT); copyleft with no alternative isn't.
        if COPYLEFT.search(lic) and not re.search(r"\bOR\b|/", lic):
            copyleft.append(f"{p['name']} {p['version']} — {lic}")
        top = os.path.dirname(p["manifest_path"])
        found = []
        for dirpath, dirnames, files in os.walk(top):
            if dirpath[len(top):].count(os.sep) > (4 if p["name"].endswith("-sys") else 0):
                dirnames[:] = []
                continue
            dirnames[:] = [d for d in dirnames if d not in ("target", ".git", "tests", "test", "examples")]
            for f in sorted(files):
                if LICENSE_FILE.match(f):
                    with open(os.path.join(dirpath, f), errors="replace") as fh:
                        found.append((os.path.relpath(os.path.join(dirpath, f), top), fh.read().strip()))
        if not found:
            missing.append(p)
        for rel, text in found:
            h = hashlib.sha1(text.encode()).hexdigest()
            texts[h] = text
            users.setdefault(h, []).append(f"{p['name']} {p['version']} ({rel})")

    out = ["Third-party Rust crates compiled into NTSCRT for Windows (ntscrt.exe),",
           "with their licenses. Generated by port/scripts/gen-licenses.py — do not edit by hand.", "",
           "Crates and their declared licenses:", ""]
    out += [f"  {p['name']} {p['version']} — {p['license'] or 'see license file'}" for p in crates]
    if missing:
        out += ["", "Crates without a license file in their package (the declared license",
                "applies; standard texts are in licenses/):", ""]
        out += [f"  {p['name']} {p['version']} — {p['license']}" for p in missing]
    for h, text in texts.items():
        out += ["", "=" * 78, "Used by:"] + [f"  {u}" for u in users[h]] + ["-" * 78, text]
    dest = os.path.join(PORT, "licenses", "rust-crates-windows.txt")
    with open(dest, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{len(crates)} crates, {len(texts)} distinct license texts, {len(missing)} without a file -> {dest}")
    if copyleft:
        sys.exit("copyleft-only licenses linked:\n  " + "\n  ".join(copyleft))


main()
